// =============================================================================
// Types
// =============================================================================

interface BeaconValidatorData {
  index: string;
  balance: string;
  status: string;
  validator: {
    pubkey: string;
    withdrawal_credentials: string;
    effective_balance: string;
    slashed: boolean;
    activation_eligibility_epoch: string;
    activation_epoch: string;
    exit_epoch: string;
    withdrawable_epoch: string;
  };
}

interface BeaconValidatorsResponse {
  data: BeaconValidatorData[];
  execution_optimistic: boolean;
  finalized: boolean;
}

// =============================================================================
// Beacon Chain Balance Fetching
// =============================================================================

/** Fallback: 69,420 ETH in Wei, used when any validator has zero balance (not yet active) */
const FALLBACK_STAKED_WEI = "69420000000000000000000";

/**
 * Fetches the total staked balance across all validators from the beacon chain.
 * Returns the total balance in Wei (beacon chain reports in Gwei, converted to Wei).
 * Falls back to 69,420 ETH if any validator has a zero balance (not yet active).
 */
export async function fetchStakedBalance(beaconApiUrl: string): Promise<string> {
  try {
    const response = await fetch(
      `${beaconApiUrl}/eth/v1/beacon/states/finalized/validators`,
      {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ ids: [...VALIDATOR_PUBLIC_KEYS] }),
      }
    );

    if (!response.ok) {
      console.warn(`Beacon API returned ${response.status}, using fallback staked balance`);
      return FALLBACK_STAKED_WEI;
    }

    const json: BeaconValidatorsResponse = await response.json();

    if (!json.data || json.data.length !== VALIDATOR_PUBLIC_KEYS.length) {
      return FALLBACK_STAKED_WEI;
    }

    let totalGwei = 0n;
    for (const validator of json.data) {
      const balance = BigInt(validator.balance);
      if (balance === 0n) {
        return FALLBACK_STAKED_WEI;
      }
      totalGwei += balance;
    }

    // Convert Gwei to Wei (1 Gwei = 1e9 Wei)
    const totalWei = totalGwei * 1_000_000_000n;
    return totalWei.toString();
  } catch (error) {
    console.error("Failed to fetch staked balance:", error);
    return FALLBACK_STAKED_WEI;
  }
}
